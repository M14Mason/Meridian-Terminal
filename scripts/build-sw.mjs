#!/usr/bin/env node
// Writes dist/sw.js after `vite build`: precaches the app shell so the app opens offline (5.8, 9.5).
// Data responses are NOT cached here; panels cache data in IndexedDB with timestamps.
import { createHash } from 'node:crypto';
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = 'dist';
const SKIP = /(^sw\.js$|\.txt$|\.map$)/;

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(DIST)
  .map((p) => relative(DIST, p).split('\\').join('/'))
  .filter((f) => !SKIP.test(f))
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const VERSION = '${version}';
const CACHE = 'meridian-shell-' + VERSION;
const BASE = self.registration.scope;
const PRECACHE = ${JSON.stringify(['./', ...files.filter((f) => f !== 'index.html')])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((p) => new URL(p, BASE).toString()))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('meridian-shell-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Only the app's own files. Proxy calls (another origin) always go to the network.
  if (url.origin !== self.location.origin || !url.href.startsWith(BASE)) return;
  if (req.mode === 'navigate') {
    // Network first so a new deploy shows up at once; cached shell when offline.
    e.respondWith(fetch(req).catch(() => caches.match(new URL('./', BASE).toString())));
    return;
  }
  // Hashed assets, fonts and icons never change under the same URL: cache first.
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js written: ${files.length} files, version ${version}`);
