/** Exact (case-insensitive) match of a table header or label against the glossary. */
export function lookupTerm(text: string): string | null {
  const t = text.trim().replace(/[▲▼:]/g, '').trim();
  if (!t || t.length > 24) return null;
  for (const [k, v] of Object.entries(GLOSSARY)) if (k.toLowerCase() === t.toLowerCase()) return `${k}: ${v}`;
  const head = t.split(/[\s(]/)[0]!;
  for (const [k, v] of Object.entries(GLOSSARY)) if (k.toLowerCase() === head.toLowerCase()) return `${k}: ${v}`;
  return null;
}
